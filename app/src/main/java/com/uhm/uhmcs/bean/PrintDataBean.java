package com.uhm.uhmcs.bean;

public class PrintDataBean {
    private String image;
    private String logo;
    private String title;
    private String describe;

    private String bottom_remarks;

    public String getImage() {
        return image;
    }

    public void setImage(String image) {
        this.image = image;
    }

    public String getLogo() {
        return logo;
    }

    public void setLogo(String logo) {
        this.logo = logo;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescribe() {
        return describe;
    }

    public void setDescribe(String describe) {
        this.describe = describe;
    }

    public String getBottom_remarks() {
        return bottom_remarks;
    }

    public void setBottom_remarks(String bottom_remarks) {
        this.bottom_remarks = bottom_remarks;
    }
}
